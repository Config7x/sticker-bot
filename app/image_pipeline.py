"""Static sticker image pipeline (Pillow only, SPEC section 7).

open -> optional background removal (rembg, guarded) -> trim -> resize so
one side is exactly 512 and the other <= 512 -> white outline + soft
shadow -> optional Persian text composed with Pillow (arabic_reshaper +
python-bidi; Persian text is NEVER generated by an image model) ->
WebP <= 512 KB.
"""
from __future__ import annotations

import glob
import io
import os

from PIL import Image, ImageDraw, ImageFilter, ImageFont, ImageOps

MAX_SIDE = 512
MAX_BYTES = 512 * 1024

_FONT_PATTERNS = [
    "/usr/share/fonts/**/NotoNaskhArabic-Bold*.ttf",
    "/usr/share/fonts/**/NotoSansArabic-Bold*.ttf",
    "/usr/share/fonts/**/NotoNaskhArabic-Regular*.ttf",
    "/usr/share/fonts/**/NotoSansArabic-Regular*.ttf",
    "/usr/share/fonts/**/NotoSansArabic*.ttf",
]

STYLE_OUTLINE = {  # style key -> (outline px, outline color, shadow strength)
    "clean": (6, (255, 255, 255, 255), 90),
    "bold": (11, (255, 255, 255, 255), 110),
    "bubble": (6, (255, 255, 255, 255), 90),
    "shadow": (4, (255, 255, 255, 255), 170),
    "neon": (7, (0, 229, 255, 255), 90),
    "minimal": (0, (255, 255, 255, 255), 0),
}


def find_font(configured: str = "") -> str | None:
    """Locate a Noto Arabic font: configured path first, then system paths."""
    if configured and os.path.exists(configured):
        return configured
    for pattern in _FONT_PATTERNS:
        for hit in sorted(glob.glob(pattern, recursive=True)):
            return hit
    return None


def shape_fa(text: str) -> str:
    """Shape + bidi Persian/Arabic text for correct Pillow rendering."""
    import arabic_reshaper
    from bidi.algorithm import get_display

    return get_display(arabic_reshaper.reshape(text))


def _try_rembg(img: Image.Image) -> Image.Image:
    """Background removal when rembg is installed; otherwise return input."""
    try:
        from rembg import remove  # type: ignore

        return remove(img)
    except Exception:
        return img


def _trim(img: Image.Image) -> Image.Image:
    bbox = img.getbbox()
    return img.crop(bbox) if bbox else img


def _fit_512(img: Image.Image) -> Image.Image:
    """Resize so the long side is exactly 512 and the other side <= 512."""
    w, h = img.size
    scale = MAX_SIDE / max(w, h)
    return img.resize((max(1, round(w * scale)), max(1, round(h * scale))),
                      Image.LANCZOS)


def _with_outline_and_shadow(img: Image.Image, style: str) -> Image.Image:
    outline_px, color, shadow_alpha = STYLE_OUTLINE.get(style, STYLE_OUTLINE["clean"])
    if outline_px <= 0 and shadow_alpha <= 0:
        return img
    pad = outline_px + 10
    canvas = Image.new("RGBA", (img.width + pad * 2, img.height + pad * 2),
                       (0, 0, 0, 0))
    alpha = img.split()[3]
    if shadow_alpha > 0:
        shadow = Image.new("RGBA", canvas.size, (0, 0, 0, 0))
        sil = Image.new("L", img.size, 0)
        sil.paste(alpha, (0, 0))
        if outline_px > 0:
            sil = sil.filter(ImageFilter.MaxFilter(outline_px * 2 + 1))
        black = Image.new("RGBA", img.size, (0, 0, 0, shadow_alpha))
        shadow.paste(black, (pad, pad + 6), sil)
        canvas.alpha_composite(shadow.filter(ImageFilter.GaussianBlur(4)))
    if outline_px > 0:
        dilated = alpha.filter(ImageFilter.MaxFilter(outline_px * 2 + 1))
        white = Image.new("RGBA", img.size, color)
        layer = Image.new("RGBA", canvas.size, (0, 0, 0, 0))
        layer.paste(white, (pad, pad), dilated)
        canvas.alpha_composite(layer)
    canvas.alpha_composite(img, (pad, pad))
    return _trim(canvas)


def _draw_text(base: Image.Image, text: str, font_path: str | None,
               style: str) -> Image.Image:
    """Compose the (already shaped) Persian text under the subject."""
    if not font_path:
        return base
    shaped = shape_fa(text)
    probe = ImageDraw.Draw(base)
    size = 64
    font = ImageFont.truetype(font_path, size)
    while size > 18:
        box = probe.textbbox((0, 0), shaped, font=font, stroke_width=2)
        if box[2] - box[0] <= base.width - 24:
            break
        size -= 4
        font = ImageFont.truetype(font_path, size)
    box = probe.textbbox((0, 0), shaped, font=font, stroke_width=2)
    tw, th = box[2] - box[0], box[3] - box[1]
    out = Image.new("RGBA", (base.width, base.height + th + 28), (0, 0, 0, 0))
    out.alpha_composite(base, (0, 0))
    d = ImageDraw.Draw(out)
    x, y = (out.width - tw) // 2 - box[0], base.height + 12 - box[1]
    if style == "bubble":
        d.rounded_rectangle([x + box[0] - 14, y + box[1] - 8,
                             x + box[2] + 14, y + box[3] + 8],
                            radius=18, fill=(255, 255, 255, 235))
        d.text((x, y), shaped, font=font, fill=(20, 20, 20, 255))
    else:
        d.text((x, y), shaped, font=font, fill=(255, 255, 255, 255),
               stroke_width=3, stroke_fill=(0, 0, 0, 255))
    return out


def _to_webp(img: Image.Image) -> bytes:
    """Encode WebP, stepping quality/scale down until <= 512 KB."""
    cur = img
    for _ in range(6):
        for quality in (92, 85, 75, 65, 55):
            buf = io.BytesIO()
            cur.save(buf, format="WEBP", quality=quality, method=6)
            data = buf.getvalue()
            if len(data) <= MAX_BYTES:
                return data
        w, h = cur.size
        cur = cur.resize((int(w * 0.9), int(h * 0.9)), Image.LANCZOS)
    return data  # best effort


def render_text_sticker(text: str, style: str = "clean",
                        font_path: str | None = None,
                        emoji: str = "") -> bytes:
    """Text-only sticker (no photo): big shaped Persian text on transparency.

    Used when the user skips the image step, and for "بساز برام" drafts.
    """
    canvas = Image.new("RGBA", (MAX_SIDE, MAX_SIDE), (0, 0, 0, 0))
    d = ImageDraw.Draw(canvas)
    lines: list[str] = []
    if emoji:
        lines.append(emoji)
    lines.append(shape_fa(text) if text else "")
    y = 150
    for line in lines:
        if not line:
            continue
        size = 110 if line == (emoji or None) else 84
        font = ImageFont.truetype(font_path, size) if font_path else None
        if font is None:
            break
        while size > 24:
            box = d.textbbox((0, 0), line, font=font, stroke_width=4)
            if box[2] - box[0] <= MAX_SIDE - 40:
                break
            size -= 6
            font = ImageFont.truetype(font_path, size)
        box = d.textbbox((0, 0), line, font=font, stroke_width=4)
        x = (MAX_SIDE - (box[2] - box[0])) // 2 - box[0]
        d.text((x, y - box[1]), line, font=font, fill=(255, 255, 255, 255),
               stroke_width=5, stroke_fill=(0, 0, 0, 255))
        y += (box[3] - box[1]) + 26
    return _to_webp(_trim(canvas))


def process_image(source: bytes | str, text: str | None = None,
                  style: str = "clean", use_rembg: bool = False,
                  font_path: str | None = None) -> bytes:
    """Full pipeline. `source` is raw image bytes or a filesystem path."""
    if isinstance(source, (str, os.PathLike)):
        img = Image.open(source)
    else:
        img = Image.open(io.BytesIO(source))
    img = ImageOps.exif_transpose(img).convert("RGBA")
    if use_rembg:
        img = _try_rembg(img)
    img = _trim(img)
    if text:
        # leave headroom: subject takes the top ~78% before text is composed
        img = _fit_512(img)
        img.thumbnail((MAX_SIDE, int(MAX_SIDE * 0.78)), Image.LANCZOS)
        img = _with_outline_and_shadow(img, style)
        img = _draw_text(img, text, font_path, style)
        if max(img.size) > MAX_SIDE:  # text may have grown the canvas
            img.thumbnail((MAX_SIDE, MAX_SIDE), Image.LANCZOS)
    else:
        img = _fit_512(img)
        img = _with_outline_and_shadow(img, style)
        if max(img.size) > MAX_SIDE:
            img = _fit_512(img)
    return _to_webp(img)
